"""
agents/content_gate.py
──────────────────────
Gatekeeper that runs BEFORE any description is generated.

It reads each document's real content, classifies how usable that content is,
and builds a deterministic, extractive "evidence profile".  Descriptions are
then produced either by an LLM (fed with the evidence) or — when no LLM is
available — straight from the evidence.  In both cases the result is
verified against the evidence ("grounding score") so an inaccurate or
fabricated description is rejected and replaced by the extractive one.

Pure stdlib; no LLM required.
"""
from __future__ import annotations

import collections
import pathlib
import re
from dataclasses import dataclass, field
from typing import Callable

# ── Status values ─────────────────────────────────────────────────────────────
OK, THIN, FAILED, UNSUPPORTED = "ok", "thin", "failed", "unsupported"

# Image types have no readable text without OCR: describe by name/path only.
NAME_ONLY_EXTS = {".png", ".jpg", ".jpeg", ".gif", ".bmp", ".webp"}

MIN_OK_CHARS = 40          # fewer (effective) characters than this → "thin"
MIN_USABLE_CHARS = 8       # a "thin" file with fewer chars than this carries no information
MIN_GROUNDING = 0.6        # minimum grounding score to accept a description

# Bump when extractive output changes so cached deterministic summaries are rebuilt once.
GATE_VERSION = 2
MAX_TOKEN_CHARS = 40  # longer "words" are binary junk / base64, not vocabulary

# Marker written into README stubs generated by generate.py. Such files restate the
# domain description, so they must never be used as evidence for that description.
STUB_MARKER = "<!-- KB:GENERATED-STUB -->"
_LEGACY_STUB_LINE = "_Add your own notes about this domain above this line._"

# Folder names that say nothing about a domain's topic.
_GENERIC_FOLDERS = set("""
sub subs misc other others old new tmp temp archive archives backup backups docs doc files data
images image img imgs assets resources untitled draft drafts
""".split())

_STOPWORDS = set("""
a about above after again all also am an and any are as at be because been before being below
between both but by can could did do does doing down during each few for from further had has have
having he her here hers him his how i if in into is it its just me more most my no nor not now of off
on once only or other our out over own same she should so some such than that the their them then
there these they this those through to too under until up very was we were what when where which
while who whom why will with would you your yes null none nan true false http https www com
slide sheet page file xlsx pptx docx pdf csv txt png jpg
""".split())

# Words that make a description read naturally but carry no factual claim.
_GENERIC = set("""
document documents folder folders file files knowledge domain contains containing covering covers
including includes related information material materials content resources resource guide guides
data details overview collection various several different mainly focused focuses topic topics
""".split())

# Terms that are frequent in business spreadsheets/decks but say nothing about
# what a document or domain is *about*.
_NOISE = set("""
total totals ibm indicates indicate customer customers amount amounts region regions view views
name names sum number numbers value values date dates quarter new old inc ltd corp llc other
unassigned continued adjusted code codes level type types list status row rows column columns
per not see use used using note notes below above america americas page sheet1 jan feb mar apr
may jun jul aug sep oct nov dec
""".split())

_BOILERPLATE_RE = re.compile(
    r"\b\d+(/\d+)*\s?pt\b|lines? maximum|sentence case|click to (add|edit)|placeholder|"
    r"lorem ipsum|delete this|your text here",
    re.IGNORECASE,
)

# Unicode-aware: a letter followed by letters/digits/+/-  (underscore splits tokens).
_TOKEN_RE = re.compile(r"[^\W\d_](?:[^\W_]|[+\-])+")
_MARKER_RE = re.compile(r"^\[(?:Slide|Sheet|Page)[^\]]*\]\s*$", re.IGNORECASE)
_SHEET_RE = re.compile(r"\[Sheet:\s*([^\]]+)\]")
_FAILED_RE = re.compile(
    r"^(\[(?!(?:Sheet|Slide|Page)\b)|(PDF|PPTX|DOCX|XLSX|IMAGE|BOXNOTE): )", re.IGNORECASE
)


# ── Data model ────────────────────────────────────────────────────────────────

@dataclass
class Evidence:
    path: pathlib.Path
    status: str
    text: str = ""
    chars: int = 0
    title: str = ""
    sheets: list[str] = field(default_factory=list)
    terms: list[str] = field(default_factory=list)
    reason: str = ""

    @property
    def usable(self) -> bool:
        if self.status == OK:
            return bool(self.text.strip())
        # A "thin" file only counts if it holds something more than a stray character.
        return self.status == THIN and self.chars >= MIN_USABLE_CHARS


# ── Helpers ───────────────────────────────────────────────────────────────────

def _tokens(text: str) -> list[str]:
    # ASCII words need 3+ chars; non-ASCII scripts (CJK, ...) are denser, 2+ is enough.
    return [
        t.lower() for t in _TOKEN_RE.findall(text)
        if (len(t) >= 3 or (len(t) >= 2 and not t.isascii())) and len(t) <= MAX_TOKEN_CHARS
    ]


def _effective_chars(text: str) -> int:
    """Length used for the thin/ok decision: non-ASCII characters carry ~3x the
    information of a Latin letter (e.g. one CJK character ≈ one word)."""
    return len(text) + 2 * sum(1 for ch in text if ord(ch) > 0x7F)


def _stem(tok: str) -> str:
    for suf in ("ing", "es", "s"):
        if tok.endswith(suf) and len(tok) - len(suf) >= 3:
            return tok[: -len(suf)]
    return tok


def _name_tokens(path: pathlib.Path) -> list[str]:
    return [t for t in _tokens(path.stem.replace("_", " ")) if t not in _STOPWORDS]


def _meaningful(tok: str) -> bool:
    return (
        tok not in _STOPWORDS
        and tok not in _NOISE
        and not any(ch.isdigit() for ch in tok)
    )


def top_terms(text: str, n: int = 8, extra: list[str] | None = None) -> list[str]:
    """Most frequent meaningful tokens; filename tokens get a fixed boost."""
    counts: collections.Counter[str] = collections.Counter(
        t for t in _tokens(text) if _meaningful(t)
    )
    for t in extra or []:
        # A filename fragment ("mig", "rev") is only a topic signal if the
        # document itself also uses the word.
        if _meaningful(t) and counts.get(t):
            counts[t] += 3
    return [t for t, _ in counts.most_common(n)]


def _first_title(text: str) -> str:
    """First line that reads like a heading (not a marker, data row or template text)."""
    for line in text.splitlines():
        s = line.strip()
        if not s or _MARKER_RE.match(s) or _BOILERPLATE_RE.search(s):
            continue
        if s.count("|") >= 2 or s.startswith("["):  # tabular data row / extractor tag
            continue
        if len(_tokens(s)) >= 2:
            return s[:100].rsplit(" ", 1)[0] if len(s) > 100 else s
    return ""


# ── Step 1: read + classify ───────────────────────────────────────────────────

def _default_extractor(path: pathlib.Path) -> str:
    from embeddings import extract_text_snippet  # lazy: agents/ is on sys.path
    return extract_text_snippet(path)


def inspect_file(
    path: pathlib.Path,
    extractor: Callable[[pathlib.Path], str] | None = None,
) -> Evidence:
    """Read the file's content and classify it. Never raises."""
    try:
        if path.stat().st_size == 0:
            return Evidence(path, FAILED, reason="file is empty (0 bytes)")
    except OSError as exc:
        return Evidence(path, FAILED, reason=f"cannot stat: {exc}")
    try:
        text = (extractor or _default_extractor)(path) or ""
    except Exception as exc:  # extraction must never break the pipeline
        return Evidence(path, FAILED, reason=f"extractor raised: {exc}")

    stripped = text.strip()
    if not stripped:
        return Evidence(path, FAILED, reason="no text extracted")
    if _FAILED_RE.match(stripped) and len(stripped) < 200:
        status = UNSUPPORTED if "nsupported" in stripped else FAILED
        return Evidence(path, status, reason=stripped[:120])
    if stripped.startswith("XLSX (large file"):
        # Nothing but a stub message: keep text empty so it is never treated as content.
        return Evidence(path, THIN, reason="file too large to read inline")

    body = "\n".join(l for l in stripped.splitlines() if not _MARKER_RE.match(l.strip()))
    real_chars = len(re.sub(r"\s+", " ", body).strip())
    status = OK if _effective_chars(re.sub(r"\s+", " ", body).strip()) >= MIN_OK_CHARS else THIN
    return Evidence(
        path=path,
        status=status,
        text=stripped,
        chars=real_chars,
        title=_first_title(stripped),
        sheets=_SHEET_RE.findall(stripped)[:6],
        terms=top_terms(stripped, 8, _name_tokens(path)),
        reason="" if status == OK else f"only {real_chars} chars of content",
    )


def scan_folder(
    folder: pathlib.Path,
    files: list[pathlib.Path],
    extractor: Callable[[pathlib.Path], str] | None = None,
) -> list[Evidence]:
    return [inspect_file(f, extractor) for f in files]


def gate_report(evidences: list[Evidence]) -> dict:
    """Counts per status plus the list of files that did not pass."""
    counts = collections.Counter(e.status for e in evidences)
    return {
        "total": len(evidences),
        **{s: counts.get(s, 0) for s in (OK, THIN, FAILED, UNSUPPORTED)},
        "flagged": [
            {"file": e.path.name, "status": e.status, "reason": e.reason}
            for e in evidences if e.status != OK
        ],
    }


# ── Step 2: extractive (no-LLM) descriptions ──────────────────────────────────

def extractive_file_summary(ev: Evidence) -> str:
    """Deterministic summary built only from text that is in the file."""
    if ev.status == THIN and ev.text.strip():
        # Too little content to extract terms from: the content itself is the summary.
        return re.sub(r"\s+", " ", ev.text).strip()[:400]
    parts: list[str] = []
    if ev.title:
        parts.append(ev.title.rstrip(".") + ".")
    if ev.sheets:
        parts.append("Sheets: " + ", ".join(ev.sheets) + ".")
    title_words = set(_tokens(ev.title or ""))
    shown = [t for t in ev.terms if t not in title_words][:6]
    if shown:
        parts.append("Key terms: " + ", ".join(shown) + ".")
    return " ".join(parts)[:400].strip() or ev.path.stem


def domain_keywords(evidences: list[Evidence], n: int = 12) -> list[str]:
    """Rank terms by how many documents they appear in, then by frequency."""
    df: collections.Counter[str] = collections.Counter()
    for e in evidences:
        if e.usable:
            df.update(dict.fromkeys(e.terms, 1))  # ordered, unique per document: deterministic ties
    return [t for t, _ in df.most_common(n)]


def _is_topic_folder(name: str) -> bool:
    n = name.strip().lower()
    return (
        len(n) >= 4 and n not in _GENERIC_FOLDERS and n not in _STOPWORDS
        and not n.startswith(".") and not n.isdigit()
    )


def _subfolders(folder_name: str, evidences: list[Evidence]) -> list[str]:
    """Top-level subfolder names under the domain folder, most populated first."""
    counts: collections.Counter[str] = collections.Counter()
    for e in evidences:
        parts = e.path.parts
        if folder_name in parts:
            rest = parts[parts.index(folder_name) + 1:-1]
            if rest and _is_topic_folder(rest[0]):
                counts[rest[0]] += 1
    return [n for n, _ in counts.most_common(4)]


def extractive_domain_meta(folder_name: str, evidences: list[Evidence]) -> dict:
    usable = [e for e in evidences if e.usable]
    types = collections.Counter(e.path.suffix.upper().lstrip(".") for e in evidences)
    type_txt = ", ".join(f"{c} {t}" for t, c in types.most_common(3))
    keywords = domain_keywords(usable)
    head = f"{folder_name}: {len(evidences)} documents ({type_txt}) covering "
    # Subfolder names are the strongest, most human-meaningful topic signal.
    topics = _subfolders(folder_name, evidences)
    chosen: list[str] = []
    for k in topics + [k for k in keywords if k.lower() not in " ".join(topics).lower()]:
        if len(head + ", ".join(chosen + [k])) > 200:
            break
        chosen.append(k)
    description = (head + ", ".join(chosen)) if chosen else head.rstrip(" covering")
    return {"description": description[:200], "keywords": keywords}


# ── Step 3: evidence for the LLM prompt ───────────────────────────────────────

def evidence_for_prompt(evidences: list[Evidence], limit: int = 20, per_file: int = 160) -> str:
    """Compact per-file evidence lines (real content, not just filenames)."""
    usable = [e for e in evidences if e.usable]
    # Spread the sample across the folder instead of taking the first N.
    step = max(1, len(usable) // limit)
    lines = []
    for e in usable[::step][:limit]:
        gist = e.title or e.text[:per_file].replace("\n", " ")
        lines.append(f"- {e.path.name} | {gist[:per_file]} | terms: {', '.join(e.terms[:5])}")
    return "\n".join(lines)


# ── Step 4: accuracy check ────────────────────────────────────────────────────

def grounding_score(description: str, evidences: list[Evidence]) -> float:
    """
    Fraction of the description's factual words that occur in the extracted
    content or filenames.  1.0 = every claim traceable; low = likely invented.
    """
    corpus: set[str] = set()
    for e in evidences:
        corpus.update(_stem(t) for t in _tokens(e.text))
        for part in e.path.parts:  # filename + every folder name in the path
            corpus.update(_stem(t) for t in _tokens(part.replace("_", " ")))
    claims = [
        _stem(t) for t in _tokens(description)
        if len(t) >= 4 and t not in _STOPWORDS and t not in _GENERIC
    ]
    if not claims:
        return 0.0
    return round(sum(1 for c in claims if c in corpus) / len(claims), 2)


_LEGACY_STUB_LINES = (_LEGACY_STUB_LINE, "_Add your own notes about this domain here._")


def _stub_text(text: str, suffix: str) -> bool:
    return STUB_MARKER in text or (
        suffix.lower() == ".md" and any(s in text for s in _LEGACY_STUB_LINES)
    )


def is_generated_stub(ev: "Evidence") -> bool:
    """True for README stubs written by generate.py (they just restate the description)."""
    return _stub_text(ev.text or "", ev.path.suffix)


def is_generated_stub_file(path: pathlib.Path) -> bool:
    """Cheap on-disk check for a generate.py README stub (only small .md files are read)."""
    if path.suffix.lower() != ".md":
        return False
    try:
        if path.stat().st_size > 20_000:
            return False
        return _stub_text(path.read_text(encoding="utf-8", errors="ignore"), ".md")
    except OSError:
        return False


def without_generated(evidences: list["Evidence"]) -> list["Evidence"]:
    return [e for e in evidences if not is_generated_stub(e)]


def is_placeholder(description: str) -> bool:
    d = (description or "").strip()
    return not d or d.startswith("Knowledge domain:")

_BARE_TYPE_RE = re.compile(
    r"^(pdf|docx?|pptx?|xlsx?|png|jpe?g|gif|boxnote|rtf|csv|txt)(\s+file)?:?\s*", re.IGNORECASE
)


def is_placeholder_summary(summary: str, path: pathlib.Path) -> bool:
    """True for summaries that carry no information about the document
    (a bare type like "XLSX file", "PPTX: name", or just the filename)."""
    s = (summary or "").strip()
    if not s:
        return True
    stem = path.stem.replace("_", " ").replace("-", " ").strip().lower()
    flat = re.sub(r"\s+", " ", s.replace("_", " ").replace("-", " ")).lower()
    if flat in (stem, path.name.lower()):
        return True
    rest = _BARE_TYPE_RE.sub("", s, count=1).strip().lower()
    rest = re.sub(r"\s+", " ", rest.replace("_", " ").replace("-", " "))
    return rest in ("", stem, path.name.lower())


def verified_or_extractive(
    candidate: str,
    evidences: list[Evidence],
    fallback: str,
    threshold: float = MIN_GROUNDING,
) -> tuple[str, str, float]:
    """
    Accept *candidate* only if it is grounded in the evidence.
    Returns (text, source, score) where source is "llm" or "extractive".
    """
    score = grounding_score(candidate, evidences) if candidate else 0.0
    if candidate and not is_placeholder(candidate) and score >= threshold:
        return candidate, "llm", score
    return fallback, "extractive", grounding_score(fallback, evidences)
